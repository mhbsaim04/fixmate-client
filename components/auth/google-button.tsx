"use client";

import { useState } from "react";
import { toast } from "sonner";
import { Button } from "@/components/ui/button";
import { authClient } from "@/lib/auth-client";

export function GoogleButton({ callbackURL }: { callbackURL: string }) {
  const [loading, setLoading] = useState(false);

  async function handle() {
    setLoading(true);
    const { error } = await authClient.signIn.social({ provider: "google", callbackURL });
    if (error) {
      toast.error(error.message ?? "Google sign-in is not available right now.");
      setLoading(false);
    }
  }

  return (
    <Button type="button" variant="outline" size="lg" className="w-full" onClick={handle} loading={loading}>
      <svg viewBox="0 0 48 48" className="!size-5" aria-hidden>
        <path fill="#FFC107" d="M43.6 20.1H42V20H24v8h11.3A12 12 0 1 1 24 12c3 0 5.8 1.1 7.9 3l5.7-5.7A20 20 0 1 0 44 24c0-1.3-.1-2.6-.4-3.9z" />
        <path fill="#FF3D00" d="m6.3 14.7 6.6 4.8A12 12 0 0 1 24 12c3 0 5.8 1.1 7.9 3l5.7-5.7A20 20 0 0 0 6.3 14.7z" />
        <path fill="#4CAF50" d="M24 44c5.2 0 9.9-2 13.4-5.2l-6.2-5.2A12 12 0 0 1 12.7 28l-6.5 5C9.5 39.6 16.2 44 24 44z" />
        <path fill="#1976D2" d="M43.6 20.1H42V20H24v8h11.3a12 12 0 0 1-4.1 5.6l6.2 5.2C37 39.2 44 34 44 24c0-1.3-.1-2.6-.4-3.9z" />
      </svg>
      Continue with Google
    </Button>
  );
}
